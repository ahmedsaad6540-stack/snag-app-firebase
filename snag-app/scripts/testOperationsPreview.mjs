import assert from 'node:assert/strict'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { mkdir } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const target = resolve(process.argv[2] || 'operations-preview.html')
const output = resolve(process.argv[3] || '/tmp/parkstreet-ops-test')
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE_PATH || undefined, args: ['--no-sandbox', '--disable-dev-shm-usage', '--no-zygote', '--single-process'], headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, acceptDownloads: true })
const errors = [], network = []
page.on('pageerror', e => errors.push(e.message))
page.on('request', req => { if (/^https?:/.test(req.url())) network.push(req.url()) })
try {
  await page.goto(pathToFileURL(target).href)
  await page.getByRole('heading', { name: 'متابعة أعمال اليوم' }).waitFor()
  assert.equal(await page.locator('tbody tr').count(), 7)
  await page.screenshot({ path: output + '/desktop.png', fullPage: true })
  await page.locator('tbody tr').filter({ hasText: 'غسيل أرضية الجراج' }).getByRole('button', { name: 'تسجيل / متابعة' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('المنفذ / المسؤول').fill('فريق الاختبار')
  await dialog.getByRole('button', { name: 'حفظ المتابعة' }).click()
  await dialog.waitFor({ state: 'hidden' })
  assert.equal(await page.locator('.ops-kpi.k1 strong').innerText(), '3')
  await page.getByLabel('التخصص', { exact: true }).selectOption('pest')
  assert.equal(await page.locator('tbody tr').count(), 1)
  assert.ok((await page.locator('tbody').innerText()).includes('صباحية'))
  await page.getByLabel('التخصص', { exact: true }).selectOption('all')
  await page.getByRole('button', { name: 'التقارير', exact: true }).click()
  await page.getByLabel('الفترة', { exact: true }).selectOption('month')
  const plannedRows = Number((await page.locator('.ops-actions .ops-muted').first().innerText()).replace(/[()]/g, ''))
  assert.ok(plannedRows > 35)
  assert.equal(await page.locator('tbody tr').count(), 35)
  const popupPromise = page.waitForEvent('popup')
  await page.getByRole('button', { name: 'طباعة / PDF' }).click()
  const popup = await popupPromise; await popup.waitForLoadState()
  assert.equal(await popup.locator('tbody tr').count(), plannedRows)
  await popup.close()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'تصدير Excel' }).click()
  const download = await downloadPromise; await download.saveAs(output + '/report.xlsx')
  await page.getByRole('button', { name: 'أعمال اليوم', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  assert.ok(await page.locator('.ops').evaluate(el => el.getBoundingClientRect().right <= window.innerWidth))
  await page.screenshot({ path: output + '/mobile.png', fullPage: true })
  assert.deepEqual(errors, [])
  assert.deepEqual(network, [])
  console.log(`PASS: desktop and mobile render, execution save, department filter, ${plannedRows} print rows, Excel download, no browser errors and no network requests`)
} finally { await browser.close() }
