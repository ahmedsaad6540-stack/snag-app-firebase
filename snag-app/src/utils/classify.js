/**
 * 🧠 التحقق الذكي: يكشف التناقضات بين الموقع والوصف
 * يُرجع قائمة تحذيرات (قد تكون فارغة إذا كل شيء منطقي)
 */
export function validateLocationDescription(locationId, desc = "") {
  const t = desc.toLowerCase().trim()
  if (!t || !locationId) return []

  const ctx = LOCATION_CONTEXT[locationId]
  if (!ctx) return []

  const warnings = []

  // تحقق من الكلمات المستحيلة في هذا الموقع
  for (const word of ctx.impossible) {
    if (t.includes(word)) {
      const customMsg = ctx.warnings[word]
      if (customMsg) {
        warnings.push(customMsg)
      } else {
        warnings.push(`⚠️ "${word}" غير متوقع في ${ctx.name} — تأكد من صحة الموقع`)
      }
    }
  }

  // تحقق إضافي من التحذيرات المخصصة (كلمات ليست بالضرورة مستحيلة لكنها مشبوهة)
  for (const [word, msg] of Object.entries(ctx.warnings)) {
    if (t.includes(word) && !warnings.includes(msg)) {
      warnings.push(msg)
    }
  }

  return warnings
}

/**
 * تصنيف شامل — يُرجع كائن يحتوي على التخصص والنوع والأولوية والتحذيرات
 * @param {string} desc - وصف المشكلة
 * @param {string} locationId - الموقع المختار حالياً (id)
 * @param {Array}  dynamicLocations - قائمة المواقع من Firestore [{ id, name, icon }]
 */
export function classifyAll(desc = "", locationId = "", dynamicLocations = []) {
  const detectedLocation = classifyLocation(desc, dynamicLocations)
  return {
    trade:    classifyTrade(desc),
    type:     classifyType(desc),
    priority: classifyPriority(desc),
    location: detectedLocation,  // null if not detected
    warnings: validateLocationDescription(locationId || detectedLocation, desc),
  }
}

/**
 * للتوافق مع الكود القديم
 */
export function classifyLocally(desc = "") {
  return classifyTrade(desc)
}
