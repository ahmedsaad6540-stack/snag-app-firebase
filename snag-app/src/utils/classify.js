/**
 * تحديد الموقع (Location) من وصف المشكلة
 * يُرجع id الموقع أو null إذا لم يتعرف
 */
export function classifyLocation(desc = "", dynamicLocations = []) {
  const t = desc.toLowerCase().trim()
  if (!t) return null

  // Check static keyword map first (more precise, longer phrases)
  const priority = ["electrical-rooms", "garage-b2", "garage-b1", "service-elevators", "passenger-elevators",
    "service-corridors", "emergency-stairs", "bathrooms", "roof", "plaza", "building-corridors"]

  for (const locId of priority) {
    const keywords = LOCATION_KEYWORDS[locId] || []
    for (const kw of keywords) {
      if (t.includes(kw.toLowerCase())) return locId
    }
  }

  // Then check dynamic locations passed from Firestore
  // Each item: { id, name, icon }
  if (Array.isArray(dynamicLocations)) {
    // Helper for fuzzy matching (handles "ة", "ال", "أ")
    const normalize = (s) => s.replace(/ال/g, "").replace(/ة/g, "ه").replace(/[أإآ]/g, "ا").trim()
    const normText = normalize(t)
    
    for (const loc of dynamicLocations) {
      const name = (loc.name || "").toLowerCase().trim()
      if (!name) continue
      
      // Exact match
      if (t.includes(name)) return loc.id
      
      // Normalized match
      const normName = normalize(name)
      if (normText.includes(normName)) return loc.id
      
      // Word intersection for multi-word locations (e.g. "غرفة المضخات" matches "غرف مضخات")
      const words = normName.split(/\s+/).filter(w => w.length > 2)
      if (words.length >= 2) {
        let matchCount = 0
        for (const w of words) {
          // If the word or a substring (like without last char) matches
          if (normText.includes(w) || normText.includes(w.slice(0, -1))) matchCount++
        }
        if (matchCount === words.length) return loc.id
      }
    }
  }

  return null
}

// ─── دوال التصنيف ───────────────────────────────────────────────────────────

function scoreMatch(text, keywords) {
  let score = 0
  for (const kw of keywords) {
    if (text.includes(kw)) score++
  }
  return score
}

/**
 * تصنيف التخصص (Trade) من وصف المشكلة
 */
export function classifyTrade(desc = "") {
  const t = desc.toLowerCase().trim()
  if (!t) return "general"

  let bestTrade = "general"
  let bestScore = 0

  for (const [trade, keywords] of Object.entries(TRADE_KEYWORDS)) {
    if (trade === "general") continue
    const score = scoreMatch(t, keywords)
    if (score > bestScore) {
      bestScore = score
      bestTrade = trade
    }
  }

  return bestTrade
}

/**
 * تصنيف النوع (Type) من وصف المشكلة: صيانة | تشغيل | نظافة
 */
export function classifyType(desc = "") {
  const t = desc.toLowerCase().trim()
  if (!t) return "maintenance"

  let bestType = "maintenance"
  let bestScore = 0

  for (const [type, keywords] of Object.entries(TYPE_KEYWORDS)) {
    const score = scoreMatch(t, keywords)
    if (score > bestScore) {
      bestScore = score
      bestType = type
    }
  }

  // إذا كان التخصص نظافة، فالنوع نظافة تلقائياً
  const trade = classifyTrade(desc)
  if (trade === "cleanliness" && bestScore === 0) {
    return "cleanliness"
  }

  return bestType
}

/**
 * تصنيف الأولوية (Priority) من وصف المشكلة
 */
export function classifyPriority(desc = "") {
  const t = desc.toLowerCase().trim()
  if (!t) return "medium"

  const urgentScore = scoreMatch(t, PRIORITY_KEYWORDS.urgent)
  if (urgentScore > 0) return "urgent"

  const mediumScore = scoreMatch(t, PRIORITY_KEYWORDS.medium)
  if (mediumScore > 0) return "medium"

  return "normal"
}

