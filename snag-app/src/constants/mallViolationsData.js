export function getArabicDayName(dateStr) {
  if (!dateStr) return ARABIC_DAYS[new Date().getDay()]
  const [y, m, d] = dateStr.split("-").map(Number)
  if (!y || !m || !d) return ARABIC_DAYS[new Date().getDay()]
  const dt = new Date(y, m - 1, d)
  return ARABIC_DAYS[dt.getDay()] || ""
}

export function formatSlashDateAr(dateStr) {
  if (!dateStr) {
    const now = new Date()
    return `${now.getFullYear()} / ${now.getMonth() + 1} / ${now.getDate()}`
  }
  const [y, m, d] = dateStr.split("-")
  if (!y || !m || !d) return dateStr
  return `${y} / ${Number(m)} / ${Number(d)}`
}

/**
 * تحويل المبلغ الرقمي بالجنيه المصري إلى صيغة قانونية بالحروف العربية
 * مثل: 1000 -> "ألف جنيهاً مصرياً فقط لا غير"
 *      2000 -> "ألفان جنيهاً مصرياً فقط لا غير"
 */
export function numberToArabicWordsEgp(amount) {
  const num = Number(amount)
  if (isNaN(num) || num <= 0) {
    return "تُقدّر قيمة المخالفة من القسم المختص طبقاً لحجم التلفيات"
  }

  const exactMap = {
    100: "مائة",
    200: "مائتا",
    300: "ثلاثمائة",
    400: "أربعمائة",
    500: "خمسمائة",
    600: "ستمائة",
    700: "سبعمائة",
    800: "ثمانمائة",
    900: "تسعمائة",
    1000: "ألف",
    1500: "ألف وخمسمائة",
    2000: "ألفان",
    2500: "ألفان وخمسمائة",
    3000: "ثلاثة آلاف",
    4000: "أربعة آلاف",
    5000: "خمسة آلاف",
    6000: "ستة آلاف",
    7000: "سبعة آلاف",
    7500: "سبعة آلاف وخمسمائة",
    8000: "ثمانية آلاف",
    9000: "تسعة آلاف",
    10000: "عشرة آلاف",
    15000: "خمسة عشر ألف",
    20000: "عشرون ألف",
    25000: "خمسة وعشرون ألف",
    30000: "ثلاثون ألف",
    40000: "أربعون ألف",
    50000: "خمسون ألف",
    100000: "مائة ألف",
  }

  if (exactMap[num]) {
    return `${exactMap[num]} جنيهاً مصرياً فقط لا غير`
  }

  const ones = ["", "واحد", "اثنان", "ثلاثة", "أربعة", "خمسة", "ستة", "سبعة", "ثمانية", "تسعة"]
  const teens = [
    "عشرة",
    "أحد عشر",
    "اثنا عشر",
    "ثلاثة عشر",
    "أربعة عشر",
    "خمسة عشر",
    "ستة عشر",
    "سبعة عشر",
    "ثمانية عشر",
    "تسعة عشر",
  ]
  const tens = ["", "عشرة", "عشرون", "ثلاثون", "أربعون", "خمسون", "ستون", "سبعون", "ثمانون", "تسعون"]
  const hundreds = [
    "",
    "مائة",
    "مائتان",
    "ثلاثمائة",
    "أربعمائة",
    "خمسمائة",
    "ستمائة",
    "سبعمائة",
    "ثمانمائة",
    "تسعمائة",
  ]

  function convertBelowThousand(n) {
    if (n === 0) return ""
    const parts = []
    const h = Math.floor(n / 100)
    const rem = n % 100
    if (h > 0) parts.push(hundreds[h])
    if (rem > 0) {
      if (rem < 10) {
        parts.push(ones[rem])
      } else if (rem < 20) {
        parts.push(teens[rem - 10])
      } else {
        const u = rem % 10
        const t = Math.floor(rem / 10)
        if (u > 0) {
          parts.push(`${ones[u]} و${tens[t]}`)
        } else {
          parts.push(tens[t])
        }
      }
    }
    return parts.join(" و")
  }

  const thousands = Math.floor(num / 1000)
  const remainder = num % 1000
  const segments = []

  if (thousands > 0) {
    if (thousands === 1) segments.push("ألف")
    else if (thousands === 2) segments.push("ألفان")
    else if (thousands >= 3 && thousands <= 10) segments.push(`${ones[thousands]} آلاف`)
    else segments.push(`${convertBelowThousand(thousands)} ألف`)
  }

  if (remainder > 0) {
    segments.push(convertBelowThousand(remainder))
  }

  return `${segments.join(" و")} جنيهاً مصرياً فقط لا غير`
}

